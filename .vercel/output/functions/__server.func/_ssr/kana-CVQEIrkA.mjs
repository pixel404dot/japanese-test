function glyphsFor(script, rows) {
	const out = [];
	for (const row of rows) for (const [hira, kata, romaji, alts = []] of ROW_PAIRS[row]) out.push({
		kana: script === "hiragana" ? hira : kata,
		romaji,
		alts,
		row,
		script
	});
	return out;
}
function glyphsForSelection(script, rows) {
	if (rows.length === 0) return [];
	if (script === "mixed") return [...glyphsFor("hiragana", rows), ...glyphsFor("katakana", rows)];
	return glyphsFor(script, rows);
}
function normalizeRomaji(value) {
	return value.toLowerCase().trim().replace(/[\s\-']/g, "");
}
function matchesRomaji(glyph, input) {
	const value = normalizeRomaji(input);
	if (!value) return false;
	return value === glyph.romaji || glyph.alts.includes(value);
}
function scriptLabel(script) {
	return script === "hiragana" ? "Hiragana" : "Katakana";
}
function scriptJa(script) {
	return script === "hiragana" ? "ひらがな" : "カタカナ";
}
